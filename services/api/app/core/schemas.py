from enum import Enum
from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field


class ProductType(str, Enum):
    LAUNCHGATE = "launchgate"
    AGENTSCOPE = "agentscope"
    EVIDENCE = "evidence"
    EVALKIT = "evalkit"


class Severity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class ReadinessStatus(str, Enum):
    PASSED = "PASSED"
    WARNING = "WARNING"
    BLOCKED = "BLOCKED"


class SourceCitation(BaseModel):
    file_path: str = Field(..., description="File path relative to repo or document title")
    line_start: Optional[int] = Field(None, description="Starting line number (1-indexed)")
    line_end: Optional[int] = Field(None, description="Ending line number (1-indexed)")
    section_title: Optional[str] = Field(None, description="Document section, table, or policy clause")
    snippet: str = Field(..., description="Exact verifiable code or text snippet from source")
    source_type: str = Field("code", description="'code', 'config', 'policy_doc', 'questionnaire', or 'test_case'")


class RemediationPrompt(BaseModel):
    title: str = Field(..., description="Short title of the fix prompt")
    description: str = Field(..., description="What this prompt instructs the AI editor to fix")
    prompt_text: str = Field(..., description="Copy-paste ready prompt formatted for Cursor, Claude, or Lovable")
    target_tool: str = Field("Cursor / Lovable", description="Suggested target editor/agent: 'Cursor / Lovable', 'Claude Code / Windsurf', 'Terminal'")


class Finding(BaseModel):
    id: str = Field(..., description="Unique finding ID, e.g., FND-LG-001")
    rule_id: str = Field(..., description="Deterministic rule ID, e.g., LG-SEC-001")
    product: ProductType = Field(..., description="Product that produced this finding")
    title: str = Field(..., description="Concise human-readable finding title")
    description: str = Field(..., description="Deterministic factual description of the issue")
    severity: Severity = Field(..., description="Finding severity level")
    category: str = Field(..., description="Category: Secret Leak, RLS Bypass, Unverified Package, Wildcard Scope, etc.")
    citation: SourceCitation = Field(..., description="Verifiable source reference")
    impact: str = Field(..., description="Exact security or compliance blast radius")
    remediation_prompt: Optional[RemediationPrompt] = Field(None, description="Copy-paste fix prompt generated by LLM explanation layer")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Rule-specific structured attributes")


class ReportSummary(BaseModel):
    total_findings: int = 0
    critical_count: int = 0
    high_count: int = 0
    medium_count: int = 0
    low_count: int = 0
    info_count: int = 0
    risk_score: int = Field(100, ge=0, le=100, description="Readiness score from 0 (critical risk) to 100 (clean/ready)")
    readiness_status: ReadinessStatus = ReadinessStatus.PASSED


class PermissionDiffItem(BaseModel):
    field: str = Field(..., description="Permission attribute or resource path")
    before_value: Any = Field(..., description="Original/active permission or scope")
    after_value: Any = Field(..., description="Recommended least-privilege permission")
    action: str = Field("RESTRICTED", description="'RESTRICTED', 'REMOVED', 'SCOPED_DOWN', or 'PROTECTED'")
    reason: str = Field(..., description="Why this permission reduction is required")


class EvidenceMappingItem(BaseModel):
    id: str = Field(..., description="Item ID, e.g. EV-MAP-001")
    question_id: str = Field(..., description="Questionnaire ID, e.g. SOC2-CC6.1")
    question: str = Field(..., description="Questionnaire requirement")
    status: str = Field(..., description="'VERIFIED_EVIDENCE' or 'UNSUPPORTED_GAP'")
    answer: str = Field(..., description="Synthesized answer strictly derived from verifiable citations")
    confidence_score: float = Field(..., ge=0.0, le=1.0)
    citation: Optional[SourceCitation] = None
    gap_reason: Optional[str] = Field(None, description="Explanation when evidence is missing/unsupported")


class EvalCaseResult(BaseModel):
    id: str = Field(..., description="Test case ID")
    test_name: str = Field(..., description="Test case or attack name")
    category: str = Field(..., description="'prompt_injection', 'jailbreak', 'canary_leak', 'tool_hijack', 'regression'")
    input_payload: str = Field(..., description="Adversarial or regression prompt payload")
    expected: str = Field(..., description="Expected behavior or rejection condition")
    actual_output: str = Field(..., description="System response or evaluated outcome")
    status: str = Field(..., description="'PASSED' or 'FAILED'")
    adversarial_type: Optional[str] = None
    defense_triggered: bool = True
    details: str = Field(..., description="Deterministic assertion or failure reasoning")


class Report(BaseModel):
    id: str = Field(..., description="Unique report ID, e.g., rpt_20261122_abc123")
    product: ProductType
    title: str
    created_at: str
    summary: ReportSummary
    findings: List[Finding] = []
    executive_summary: str = Field(..., description="Plain-English summary synthesized by Engine 2 from deterministic findings")
    remediation_prompts: List[RemediationPrompt] = []
    permission_diff: Optional[List[PermissionDiffItem]] = None
    evidence_matrix: Optional[List[EvidenceMappingItem]] = None
    eval_results: Optional[List[EvalCaseResult]] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ScanInputFile(BaseModel):
    filename: str
    content: str
    file_type: Optional[str] = None


class ScanRequest(BaseModel):
    product: ProductType
    project_name: str = "Demo Project"
    files: List[ScanInputFile] = []
    raw_content: Optional[str] = None
    options: Dict[str, Any] = Field(default_factory=dict)
    ephemeral: bool = Field(
        False,
        description="Zero-Retention Mode: run the scan in memory and return the report without persisting inputs or findings",
    )


class IngestSkippedFile(BaseModel):
    path: str = Field(..., description="Path of the skipped entry inside the upload or archive")
    reason: str = Field(
        ...,
        description="'excluded_directory', 'binary', 'too_large', 'file_limit', 'size_limit', 'not_a_regular_file', or 'encrypted'",
    )


class IngestResponse(BaseModel):
    source: str = Field(..., description="'upload' or 'github:<owner>/<repo>@<ref>'")
    files: List[ScanInputFile] = Field(default_factory=list, description="Extracted text files ready to pass to POST /run/{product}")
    skipped: List[IngestSkippedFile] = Field(default_factory=list, description="Sample of skipped entries (capped)")
    skipped_count: int = Field(0, description="Total number of skipped entries")
    total_bytes: int = Field(0, description="Total UTF-8 size of the extracted text")
    truncated: bool = Field(False, description="True when file-count or size limits dropped part of the input")


class GithubIngestRequest(BaseModel):
    repo_url: str = Field(..., description="Public repository URL, e.g. https://github.com/owner/repo")
    ref: Optional[str] = Field(None, description="Branch, tag, or commit SHA (defaults to the default branch)")


class BillingTier(str, Enum):
    PER_SCAN = "per_scan"
    PRO_MONTHLY = "pro_monthly"
    ENTERPRISE_MONTHLY = "enterprise_monthly"


class BillingCheckoutRequest(BaseModel):
    tier: BillingTier = BillingTier.PER_SCAN
    success_url: Optional[str] = None
    cancel_url: Optional[str] = None


class BillingCheckoutResponse(BaseModel):
    checkout_url: str
    session_id: str
    is_mock: bool = True
    message: str


class BillingStatusResponse(BaseModel):
    tier: str = Field(..., description="'free', 'per_scan', 'pro_monthly', or 'enterprise'")
    credits_remaining: int
    is_mock: bool
    subscription_active: bool
    free_preview_available: bool = Field(True, description="The one free preview scan has not been used yet")
    can_run_full_scan: bool = Field(False, description="An active subscription or at least one scan credit")

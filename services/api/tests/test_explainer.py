class FakeModels:
    """Stands in for ``genai.Client().models``; records every call."""

    def __init__(self, text: Optional[str] = None, error: Optional[BaseException] = None, delay: float = 0.0) -> None:
        self.text, self.error, self.delay = text, error, delay
        self.calls: List[Dict[str, Any]] = []

    def generate_content(self, *, model: str, contents: Any, config: Any) -> Any:
        self.calls.append({"model": model, "contents": contents, "config": config})
        if self.delay:
            time.sleep(self.delay)
        if self.error is not None:
            raise self.error
        return SimpleNamespace(text=self.text)


def _client(**kwargs: Any) -> Any:
    return SimpleNamespace(models=FakeModels(**kwargs))


